import { useState } from "react";

// Three short steps, each with a looping clip cut from the demo videos (public/demos/*.webm).
const STEPS = [
  { clip: "check", title: "Check your work", body: "On any homework page, press Check my work (or Alt+Shift+C). StudyLens circles mistakes right on the page." },
  { clip: "ask", title: "Ask about anything", body: "Open Ask to get an explanation of what's on your screen, with steps and graphs that animate in." },
  { clip: "practice", title: "Practice what you missed", body: "Practice writes problems aimed at your mistakes and brings them back right before you'd forget." },
] as const;

// Clips are generated by demo/ into public/demos, so their paths aren't in WXT's typed list yet.
const clipUrl = (name: string) => (browser.runtime.getURL as (p: string) => string)(`/demos/${name}.webm`);

export const firstRunDone =storage.defineItem<boolean>("local:firstRunDone", { fallback: false });

export function FirstRun({ onDone }: { onDone: () => void }) {
  const [i, setI] = useState(0);
  const [clipMissing, setClipMissing] = useState(false);
  const step = STEPS[i];
  const last = i === STEPS.length - 1;
  const finish = async () => {
    await firstRunDone.setValue(true);
    onDone();
  };
  return (
    <div className="sl-firstrun">
      <div className="sl-firstrun-steps" aria-hidden="true">
        {STEPS.map((s, k) => (
          <span key={s.clip} className={k <= i ? "on" : ""} />
        ))}
      </div>
      {!clipMissing && <video key={step.clip} src={clipUrl(step.clip)} autoPlay muted loop playsInline onError={() => setClipMissing(true)} aria-label={step.title} />}
      <div>
        <h2 className="sl-h2">{step.title}</h2>
        <p className="sl-muted" style={{ margin: "4px 0 0" }}>
          {step.body}
        </p>
      </div>
      <div className="sl-row" style={{ justifyContent: "space-between" }}>
        <button className="sl-link" onClick={finish}>
          Skip
        </button>
        <button className="sl-btn" onClick={() => (last ? finish() : setI(i + 1))}>
          {last ? "Got it" : "Next"}
        </button>
      </div>
    </div>
  );
}
