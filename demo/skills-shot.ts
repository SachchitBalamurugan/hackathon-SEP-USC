import { chromium } from "playwright";
import { DEMO_EMAIL, DEMO_PASSWORD, SITE } from "./lib";
const out = process.argv[2];
const browser = await chromium.launch({ args: ["--use-angle=swiftshader", "--enable-unsafe-swiftshader"] });
const page = await browser.newPage({ viewport: { width: 1440, height: 900 } });
const errors: string[] = [];
page.on("console", (m) => m.type() === "error" && !m.text().includes("404") && errors.push(m.text().slice(0, 160)));
await page.goto(`${SITE}/login`);
await page.fill('input[name="email"]', DEMO_EMAIL);
await page.fill('input[name="password"]', DEMO_PASSWORD);
await page.click('button:has-text("Sign in")');
await page.waitForURL("**/dashboard");
await page.goto(`${SITE}/dashboard/skills`, { waitUntil: "networkidle" });
await page.waitForTimeout(3000);
await page.screenshot({ path: `${out}/skills-a.png` });
await page.click("text=distributing a negative");
await page.waitForTimeout(1500);
await page.screenshot({ path: `${out}/skills-b.png` });
await page.goto(`${SITE}/dashboard/privacy`, { waitUntil: "networkidle" });
await page.screenshot({ path: `${out}/privacy.png`, fullPage: true });
console.log("errors:", errors.length ? errors.join("\n") : "none");
await browser.close();
